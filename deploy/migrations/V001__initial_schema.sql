-- AI 字幕纪要参考后端的最小 PostgreSQL 事实源。
--
-- 这份迁移同时适用于 Compose 启动的 PostgreSQL 和 CZUR/合作伙伴管理的
-- 外部 PostgreSQL。迁移脚本会在成功执行后登记版本；因此本文件只负责
-- 建表和约束，不写入任何默认用户、Token、模型密钥或业务数据。

BEGIN;

CREATE TABLE IF NOT EXISTS meeting (
    meeting_id              TEXT PRIMARY KEY,
    deployment_scope        TEXT NOT NULL,
    client_session_id       TEXT NOT NULL,
    subject_scope           TEXT NOT NULL,
    profile_id              TEXT NOT NULL,
    profile_revision        INTEGER NOT NULL CHECK (profile_revision > 0),
    state                   TEXT NOT NULL,
    aggregate_version       BIGINT NOT NULL DEFAULT 0 CHECK (aggregate_version >= 0),
    finalization_receipt_id TEXT,
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ NOT NULL,
    deleted_at              TIMESTAMPTZ,
    metadata                JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT meeting_updated_after_created
        CHECK (updated_at >= created_at)
);

-- 同一个部署范围内，客户端会话只能成功创建一个会议。客户端重试仍通过
-- idempotency_record 返回原响应，不依赖“先查后插”的应用层竞态窗口。
CREATE UNIQUE INDEX IF NOT EXISTS meeting_scope_session_uq
    ON meeting (deployment_scope, client_session_id);

CREATE INDEX IF NOT EXISTS meeting_scope_state_idx
    ON meeting (deployment_scope, state, updated_at);

CREATE TABLE IF NOT EXISTS meeting_event (
    meeting_id      TEXT NOT NULL REFERENCES meeting (meeting_id),
    event_sequence  BIGINT NOT NULL CHECK (event_sequence > 0),
    event_id        TEXT NOT NULL,
    event_type      TEXT NOT NULL,
    payload         JSONB NOT NULL,
    occurred_at     TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (meeting_id, event_sequence),
    CONSTRAINT meeting_event_id_uq UNIQUE (event_id)
);

CREATE TABLE IF NOT EXISTS meeting_stream (
    meeting_id       TEXT NOT NULL REFERENCES meeting (meeting_id),
    stream_id        TEXT NOT NULL,
    last_client_seq  BIGINT NOT NULL DEFAULT 0 CHECK (last_client_seq >= 0),
    last_server_seq  BIGINT NOT NULL DEFAULT 0 CHECK (last_server_seq >= 0),
    input_state      TEXT NOT NULL DEFAULT 'OPEN',
    updated_at       TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (meeting_id, stream_id)
);

CREATE TABLE IF NOT EXISTS workflow_step (
    step_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id        TEXT NOT NULL REFERENCES meeting (meeting_id),
    step_type         TEXT NOT NULL,
    step_key          TEXT NOT NULL,
    status            TEXT NOT NULL,
    attempt_count     INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    lease_owner       TEXT,
    lease_until       TIMESTAMPTZ,
    input_artifact_id TEXT,
    output_artifact_id TEXT,
    error_code        TEXT,
    error_message     TEXT,
    updated_at        TIMESTAMPTZ NOT NULL,
    CONSTRAINT workflow_step_key_uq UNIQUE (meeting_id, step_type, step_key)
);

CREATE INDEX IF NOT EXISTS workflow_step_claim_idx
    ON workflow_step (status, lease_until, updated_at);

CREATE TABLE IF NOT EXISTS artifact (
    artifact_id        TEXT PRIMARY KEY,
    meeting_id         TEXT NOT NULL REFERENCES meeting (meeting_id),
    artifact_type      TEXT NOT NULL,
    revision           INTEGER NOT NULL CHECK (revision > 0),
    content_type       TEXT NOT NULL,
    byte_length        BIGINT CHECK (byte_length IS NULL OR byte_length >= 0),
    storage_binding_id TEXT NOT NULL,
    sha256             TEXT,
    metadata           JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT artifact_revision_uq UNIQUE (meeting_id, artifact_type, revision)
);

CREATE TABLE IF NOT EXISTS usage_reservation (
    reservation_id TEXT PRIMARY KEY,
    meeting_id     TEXT NOT NULL REFERENCES meeting (meeting_id),
    usage_type     TEXT NOT NULL,
    status         TEXT NOT NULL,
    quantity       NUMERIC(20, 6) NOT NULL CHECK (quantity >= 0),
    provider_ref   TEXT,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT usage_reservation_meeting_type_uq UNIQUE (meeting_id, usage_type)
);

CREATE TABLE IF NOT EXISTS idempotency_record (
    subject_scope  TEXT NOT NULL,
    idempotency_key TEXT NOT NULL,
    request_hash   TEXT NOT NULL,
    response_status INTEGER,
    response_body  JSONB,
    created_at     TIMESTAMPTZ NOT NULL,
    expires_at     TIMESTAMPTZ,
    PRIMARY KEY (subject_scope, idempotency_key),
    CONSTRAINT idempotency_expiry_ck
        CHECK (expires_at IS NULL OR expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idempotency_expiry_idx
    ON idempotency_record (expires_at);

CREATE TABLE IF NOT EXISTS outbox_event (
    event_id       TEXT PRIMARY KEY,
    aggregate_type TEXT NOT NULL,
    aggregate_id   TEXT NOT NULL,
    event_type     TEXT NOT NULL,
    payload        JSONB NOT NULL,
    occurred_at    TIMESTAMPTZ NOT NULL,
    available_at   TIMESTAMPTZ NOT NULL,
    status         TEXT NOT NULL DEFAULT 'PENDING',
    attempt_count  INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    lease_owner    TEXT,
    lease_until    TIMESTAMPTZ,
    published_at   TIMESTAMPTZ,
    last_error     TEXT,
    CONSTRAINT outbox_status_ck
        CHECK (status IN ('PENDING', 'LEASED', 'PUBLISHED', 'DEAD'))
);

CREATE INDEX IF NOT EXISTS outbox_claim_idx
    ON outbox_event (status, available_at, lease_until);

CREATE TABLE IF NOT EXISTS plugin_execution (
    execution_id   TEXT PRIMARY KEY,
    meeting_id     TEXT REFERENCES meeting (meeting_id),
    plugin_id      TEXT NOT NULL,
    plugin_version TEXT NOT NULL,
    operation      TEXT NOT NULL,
    status         TEXT NOT NULL,
    request_id     TEXT,
    started_at     TIMESTAMPTZ NOT NULL,
    finished_at    TIMESTAMPTZ,
    error_code     TEXT,
    metadata       JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS schema_migrations (
    version     TEXT PRIMARY KEY,
    applied_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
